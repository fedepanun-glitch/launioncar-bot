-- 1) Datos de membrete en cada empresa (La Unión Car y Vyron)
alter table public.empresas
  add column if not exists razon_social text,
  add column if not exists nombre_fantasia text,
  add column if not exists condicion_iva text,
  add column if not exists ingresos_brutos text,
  add column if not exists inicio_actividades text,
  add column if not exists domicilio text,
  add column if not exists localidad text,
  add column if not exists telefono text,
  add column if not exists email text,
  add column if not exists web text,
  add column if not exists banco text,
  add column if not exists cbu text,
  add column if not exists alias_cbu text,
  add column if not exists leyenda_presupuesto text,
  add column if not exists logo text;

-- 2) Tabla de presupuestos
create table if not exists public.presupuestos (
  id                 uuid primary key default gen_random_uuid(),
  numero             bigint generated by default as identity unique,
  empresa_id         uuid references public.empresas(id),
  tercero_id         uuid references public.terceros(id) on delete set null,
  cliente_nombre     text not null,
  cliente_cuit       text,
  cliente_contacto   text,
  fecha              date not null default current_date,
  validez_dias       int not null default 7,
  estado             text not null default 'borrador' check (estado in ('borrador','enviado','aceptado','rechazado')),
  modo_iva           text not null default 'mas_iva' check (modo_iva in ('mas_iva','iva_incluido','sin_iva')),
  lugar_entrega      text,
  condicion_pago     text,
  mostrar_por_litro  boolean not null default true,
  items              jsonb not null default '[]'::jsonb,
  subtotal           numeric,
  iva                numeric,
  total              numeric,
  condiciones        text,
  notas_internas     text,
  creado_por         text default (auth.jwt() ->> 'email'),
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
create index if not exists presupuestos_tercero_idx on public.presupuestos (tercero_id);

-- 3) Permisos: todos ven, admin y carga arman, solo admin borra
alter table public.presupuestos enable row level security;
drop policy if exists "rol_ver" on public.presupuestos;
create policy "rol_ver" on public.presupuestos for select to authenticated
  using (public.mi_rol() in ('admin','carga','lectura'));
drop policy if exists "rol_cargar" on public.presupuestos;
create policy "rol_cargar" on public.presupuestos for insert to authenticated
  with check (public.mi_rol() in ('admin','carga'));
drop policy if exists "rol_editar" on public.presupuestos;
create policy "rol_editar" on public.presupuestos for update to authenticated
  using (public.mi_rol() in ('admin','carga')) with check (public.mi_rol() in ('admin','carga'));
drop policy if exists "rol_borrar" on public.presupuestos;
create policy "rol_borrar" on public.presupuestos for delete to authenticated
  using (public.mi_rol() = 'admin');
grant select, insert, update, delete on public.presupuestos to authenticated;
